from flask import Blueprint, request, jsonify
from app.models.user import User

def user_blueprint():
    user_bp = Blueprint('user', __name__)

    @user_bp.route('/users', methods=['GET'])
    def get_users():
        # Normally, you would interact with the database here, but since there's no database layer, we simulate a response
        mock_users = [
            {"id": 1, "name": "Alice", "email": "alice@example.com"},
            {"id": 2, "name": "Bob", "email": "bob@example.com"}
        ]
        return jsonify(mock_users), 200

    @user_bp.route('/users', methods=['POST'])
    def create_user():
        data = request.get_json()
        if not data or not all(key in data for key in ['name', 'email']):
            return jsonify({"error": "Invalid input"}), 400

        # Simulate a new user creation
        new_user = {
            "id": 3,  # Normally generated by the database
            "name": data['name'],
            "email": data['email']
        }
        return jsonify(new_user), 201

    @user_bp.route('/users/<int:user_id>', methods=['GET'])
    def get_user(user_id):
        # Simulate fetching a single user
        if user_id == 1:
            user = {"id": 1, "name": "Alice", "email": "alice@example.com"}
        elif user_id == 2:
            user = {"id": 2, "name": "Bob", "email": "bob@example.com"}
        else:
            return jsonify({"error": "User not found"}), 404

        return jsonify(user), 200

    return user_bp